# Exercício 2: Lista de Strings
# Crie uma lista com 5 nomes e:
# - exiba todos os nomes
# - exiba o primeiro e o último nome
# - conte quantos nomes existem

# Criando a lista com 5 nomes
nomes = ["Ana", "Bruno", "Carla", "Daniel", "Elisa"]

# Exibindo todos os nomes
print(f"Todos os nomes na lista: {nomes}")

# Exibindo o primeiro e o último nome
print(f"Primeiro nome: {nomes[0]}")
print(f"Último nome: {nomes[-1]}")

# Contando quantos nomes existem
quantidade = len(nomes)
print(f"Quantidade de nomes na lista: {quantidade}")
