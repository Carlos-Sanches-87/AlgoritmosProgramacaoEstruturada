# Exercício 1: Lista de Inteiros
# Crie uma lista com 5 números inteiros e exiba:
# - todos os valores
# - o maior número
# - o menor número

# Criando a lista com 5 números inteiros
numeros = [12, 45, 7, 89, 23]

# Exibindo todos os valores
print(f"Todos os valores da lista: {numeros}")

# Exibindo o maior número
maior_numero = max(numeros)
print(f"O maior número é: {maior_numero}")

# Exibindo o menor número
menor_numero = min(numeros)
print(f"O menor número é: {menor_numero}")
